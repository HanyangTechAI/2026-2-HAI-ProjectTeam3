class PublicKeyPreservationTests(unittest.TestCase):
    # Structurally valid public-key records for testing text handling only;
    # no private key material is present or generated by these tests.
    @staticmethod
    def public_key(fill):
        algorithm = b"ssh-ed25519"
        data = struct.pack(">I", len(algorithm)) + algorithm + struct.pack(">I", 32) + bytes([fill]) * 32
        return "ssh-ed25519 " + base64.b64encode(data).decode("ascii")

    def test_append_is_idempotent_and_preserves_existing_restricted_key(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary) / ".ssh"
            directory.mkdir()
            first, second = self.public_key(1), self.public_key(2)
            old = f'from="192.0.2.0/24",no-agent-forwarding {first} existing-restricted-key'
            path = directory / "authorized_keys"
            path.write_text(old)
            payload = first + " same-key-no-restrictions\n" + second + " newly-injected\n"
            self.assertEqual(ssh_auth.authorize(directory, payload), 1)
            expected = old + "\n" + second + " newly-injected\n"
            self.assertEqual(path.read_text(), expected)
            self.assertEqual(ssh_auth.authorize(directory, payload), 0)
            self.assertEqual(path.read_text(), expected)
            self.assertEqual(path.stat().st_mode & 0o777, 0o600)

    def test_empty_or_invalid_payload_does_not_modify_existing_keys(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary) / ".ssh"
            self.assertEqual(ssh_auth.authorize(directory, ""), 0)
            self.assertFalse(directory.exists())
            directory.mkdir()
            path = directory / "authorized_keys"
            path.write_text("existing keys\n")
            with self.assertRaises(ValueError):
                ssh_auth.authorize(directory, "not a public key")
            self.assertEqual(path.read_text(), "existing keys\n")

    def test_existing_authorized_keys_symlink_is_never_followed_for_writes(self):
        with tempfile.TemporaryDirectory() as temporary:
            directory = Path(temporary) / ".ssh"
            directory.mkdir()
            external = Path(temporary) / "shared-key-list"
            external.write_text("user-owned original\n")
            (directory / "authorized_keys").symlink_to(external)
            self.assertEqual(ssh_auth.authorize(directory, self.public_key(3)), 0)
            self.assertEqual(external.read_text(), "user-owned original\n")


@unittest.skipUnless(shutil.which("git"), "Git is required for offline clone tests")
class DockerRuntimeTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.seed = self.root / "seed"
        self.seed.mkdir()
        self.git("init", "--quiet", "--initial-branch=main")
        self.git("config", "user.email", "runtime-test@example.invalid")
        self.git("config", "user.name", "Runtime Test")
        (self.seed / "data").mkdir()
        (self.seed / "data/README.md").write_text("Tracked dataset instructions\n")
        (self.seed / "README.md").write_text("initial main\n")
        (self.seed / ".gitignore").write_text("/data/*\n!/data/README.md\nmodels/\noutputs/\nthird_party/\n")
        self.git("add", ".")
        self.git("commit", "--quiet", "-m", "initial main")
        first_commit = self.git("rev-parse", "HEAD")
        branches = {"main": {"commit": first_commit, "environment": "main"}}
        for name, environment in (("feat/generation-midterm", "main"),
                                  ("feat/raspi-fastapi-pipeline", "web"),
                                  ("feat/raspi-client", "web")):
            self.git("checkout", "--quiet", "-b", name, first_commit)
            (self.seed / "README.md").write_text(name + "\n")
            self.git("add", "README.md")
            self.git("commit", "--quiet", "-m", name)
            branches[name] = {"commit": self.git("rev-parse", "HEAD"), "environment": environment}
        self.git("checkout", "--quiet", "main")
        self.environments = {}
        for name in ("main", "web", "m1"):
            root = self.root / "venv" / name
            (root / "bin").mkdir(parents=True)
            (root / "bin/python").symlink_to(sys.executable)
            (root / "pyvenv.cfg").write_text(f"version = test-{name}\n")
            self.environments[name] = str(root)
        self.sam = self.root / "sam"
        self.sam.mkdir()
        self.lora = self.root / "train_text_to_image_lora.py"
        self.lora.write_text("# pinned external training script\n")
        self.value = {
            "schema_version": 1,
            "repository_url": "https://github.com/example/project.git",
            "source_seed": str(self.seed),
            "default_branch": "main",
            "branches": branches,
            "environments": self.environments,
            "assets": {"sam_repository": str(self.sam), "lora_training_script": str(self.lora)},
        }
        self.config = hai.Configuration(self.value)
        self.workspace = self.root / "workspace"
        self.runtime = hai.Runtime(self.config, self.workspace)

    def git(self, *arguments, cwd=None):
        result = subprocess.run(["git", "-c", "core.hooksPath=/dev/null", "-C", str(cwd or self.seed),
                                 *arguments], text=True, capture_output=True, check=True)
        return result.stdout.strip()

    def write_config(self):
        path = self.root / "branches.json"
        path.write_text(json.dumps(self.value))
        return path

    def test_each_checkout_uses_pinned_commit_even_when_seed_branch_has_moved(self):
        (self.seed / "README.md").write_text("newer seed main\n")
        self.git("add", "README.md")
        self.git("commit", "--quiet", "-m", "unpublished later main")
        paths = self.runtime.setup(list(self.value["branches"]))
        for name, path in zip(self.value["branches"], paths):
            self.assertEqual(self.git("rev-parse", "HEAD", cwd=path), self.value["branches"][name]["commit"])
            self.assertEqual(self.git("branch", "--show-current", cwd=path), name)
            self.assertEqual(self.git("remote", "get-url", "origin", cwd=path), self.value["repository_url"])
            self.assertFalse((path / ".git/objects/info/alternates").exists())
        self.assertEqual((paths[0] / "README.md").read_text(), "initial main\n")

    def test_repeated_setup_preserves_staged_unstaged_and_untracked_work(self):
        path, = self.runtime.setup(["main"])
        (path / "README.md").write_text("staged user work\n")
        self.git("add", "README.md", cwd=path)
        (path / "README.md").write_text("further unstaged user work\n")
        (path / "notes.txt").write_text("untracked notes\n")
        before_status = self.git("status", "--porcelain", cwd=path)
        before_index = self.git("show", ":README.md", cwd=path)
        self.runtime.setup(["main"])
        self.assertEqual(self.git("status", "--porcelain", cwd=path), before_status)
        self.assertEqual(self.git("show", ":README.md", cwd=path), before_index)
        self.assertEqual((path / "README.md").read_text(), "further unstaged user work\n")
        self.assertEqual((path / "notes.txt").read_text(), "untracked notes\n")

    def test_existing_custom_branch_and_commits_are_never_reset(self):
        path, = self.runtime.setup(["main"])
        self.git("checkout", "--quiet", "-b", "my-experiment", cwd=path)
        (path / "README.md").write_text("custom experiment\n")
        self.git("add", "README.md", cwd=path)
        self.git("-c", "user.name=Runtime Test", "-c", "user.email=runtime-test@example.invalid",
                 "commit", "--quiet", "-m", "my experiment", cwd=path)
        head = self.git("rev-parse", "HEAD", cwd=path)
        self.runtime.setup(["main"])
        self.assertEqual(self.git("branch", "--show-current", cwd=path), "my-experiment")
        self.assertEqual(self.git("rev-parse", "HEAD", cwd=path), head)
        self.assertTrue(any("my-experiment" in text for text in self.runtime.warnings))

    def test_checkout_changes_are_isolated_and_seed_can_be_removed(self):
        main, other = self.runtime.setup(["main", "feat/generation-midterm"])
        (main / "README.md").write_text("isolated change\n")
        self.assertEqual((other / "README.md").read_text(), "feat/generation-midterm\n")
        shutil.rmtree(self.seed)
        self.assertEqual(self.git("show", "HEAD:README.md", cwd=main), "initial main")

    def test_data_readme_is_preserved_models_shared_outputs_isolated(self):
        main, other = self.runtime.setup(["main", "feat/generation-midterm"])
        self.assertFalse((main / "data").is_symlink())
        self.assertEqual((main / "data/README.md").read_text(), "Tracked dataset instructions\n")
        self.assertEqual((main / "data/lora").resolve(), (other / "data/lora").resolve())
        self.assertEqual((main / "models").resolve(), (other / "models").resolve())
        self.assertNotEqual((main / "outputs").resolve(), (other / "outputs").resolve())
        (main / "models/weight.bin").write_bytes(b"user weights")
        self.assertEqual((other / "models/weight.bin").read_bytes(), b"user weights")
        (main / "outputs/result.txt").write_text("first branch only")
        self.assertFalse((other / "outputs/result.txt").exists())
        self.assertEqual((main / "outputs/age_lora_tools/train_text_to_image_lora.py").resolve(), self.lora)
        self.assertEqual((main / "third_party/SAM").resolve(), self.sam)

    def test_existing_assets_and_broken_symlinks_are_retained(self):
        path, = self.runtime.setup(["main"])
        (path / "models").unlink()
        (path / "models").mkdir()
        (path / "models/my-weight.bin").write_bytes(b"must survive")
        (path / "data/lora").unlink()
        external = self.root / "not-present-yet"
        (path / "data/lora").symlink_to(external)
        self.runtime.setup(["main"])
        self.assertEqual((path / "models/my-weight.bin").read_bytes(), b"must survive")
        self.assertFalse((path / "models").is_symlink())
        self.assertEqual(os.readlink(path / "data/lora"), str(external))
        self.assertFalse(external.exists())
        self.assertTrue(any("Preserved existing asset" in text for text in self.runtime.warnings))

    def test_existing_output_symlink_is_not_followed_when_seeding_tools(self):
        path, = self.runtime.setup(["main"])
        external = self.root / "my-output"
        external.mkdir()
        (external / "keep.txt").write_text("keep")
        (path / "outputs").unlink()
        (path / "outputs").symlink_to(external)
        self.runtime.setup(["main"])
        self.assertEqual(list(external.iterdir()), [external / "keep.txt"])
        self.assertEqual((path / "outputs").resolve(), external)

    def test_shared_data_cannot_hide_a_tracked_child(self):
        (self.seed / "data/contract").mkdir()
        (self.seed / "data/contract/schema.json").write_text("{}")
        self.git("add", "--force", "data/contract/schema.json")
        self.git("commit", "--quiet", "-m", "track dataset contract")
        value = copy.deepcopy(self.value)
        value["branches"]["main"]["commit"] = self.git("rev-parse", "HEAD")
        runtime = hai.Runtime(hai.Configuration(value), self.workspace)
        (self.workspace / "shared/data/contract").mkdir(parents=True)
        (self.workspace / "shared/data/contract/extra.bin").write_bytes(b"shared")
        path, = runtime.setup(["main"])
        self.assertFalse((path / "data/contract").is_symlink())
        self.assertEqual((path / "data/contract/schema.json").read_text(), "{}")
        self.assertFalse((path / "data/contract/extra.bin").exists())

    def test_unknown_or_traversing_branch_rejected_before_workspace_creation(self):
        for name in ("../outside", "/absolute", "feat/not-listed"):
            with self.subTest(name=name):
                with self.assertRaises(hai.HaiError):
                    self.runtime.setup([name])
                self.assertFalse(self.workspace.exists())
        for name in ("../bad", "feat/../bad", "feat//bad", "bad.lock", "-x"):
            value = copy.deepcopy(self.value)
            value["branches"][name] = value["branches"]["main"]
            with self.subTest(manifest_name=name), self.assertRaises(hai.HaiError):
                hai.Configuration(value)

    def test_slug_collisions_and_relative_workspace_paths_are_rejected(self):
        value = copy.deepcopy(self.value)
        value["branches"]["feat--raspi-client"] = value["branches"]["main"]
        with self.assertRaisesRegex(hai.HaiError, "collision"):
            hai.Configuration(value)
        for path in (Path("relative"), Path("/"), self.root / ".." / "outside"):
            with self.subTest(path=str(path)), self.assertRaises(hai.HaiError):
                hai.Runtime(self.config, path)

    def test_managed_checkout_symlinks_are_rejected_without_modifying_target(self):
        external = self.root / "external"
        external.mkdir()
        (external / "keep").write_text("untouched")
        (self.workspace / "branches").mkdir(parents=True)
        (self.workspace / "branches/main").symlink_to(external)
        with self.assertRaises(hai.HaiError):
            self.runtime.setup(["main"])
        self.assertEqual(list(external.iterdir()), [external / "keep"])
        self.assertEqual((external / "keep").read_text(), "untouched")

    def test_env_mapping_filters_old_venv_and_keeps_explicit_shared_caches(self):
        inherited = {"PATH": f"{self.environments['main']}/bin:/old-venv/bin:/usr/bin",
                     "VIRTUAL_ENV": "/old-venv", "PYTHONHOME": "/wrong-python", "PYTHONPATH": "/wrong-modules",
                     "HF_HOME": "/custom/hf-cache", "TORCH_HOME": "/custom/torch-cache"}
        with mock.patch.dict(os.environ, inherited, clear=True):
            for branch in self.value["branches"]:
                env = self.runtime.environment(branch)
                expected = self.value["branches"][branch]["environment"]
                self.assertEqual(env["HAI_ENV"], expected)
                self.assertEqual(env["PATH"].split(os.pathsep)[0], self.environments[expected] + "/bin")
                self.assertNotIn("/old-venv/bin", env["PATH"])
                self.assertNotIn("PYTHONHOME", env)
                self.assertNotIn("PYTHONPATH", env)
                self.assertEqual(env["HF_HOME"], "/custom/hf-cache")
                self.assertEqual(env["TORCH_HOME"], "/custom/torch-cache")
            main = self.runtime.environment("main")
            m1 = self.runtime.environment("main", "m1")
            web = self.runtime.environment("feat/raspi-client")
        self.assertEqual(m1["VIRTUAL_ENV"], self.environments["m1"])
        self.assertEqual(len({env["TORCH_EXTENSIONS_DIR"] for env in (main, m1, web)}), 3)

    def test_run_cli_executes_in_correct_workspace_and_environment(self):
        config = self.write_config()
        script = "import os,json; print(json.dumps({'cwd':os.getcwd(),'env':os.environ['HAI_ENV'],'venv':os.environ['VIRTUAL_ENV']}))"
        env = dict(os.environ, HAI_CONFIG=str(config), HAI_WORKSPACE=str(self.workspace))
        result = subprocess.run([sys.executable, str(MODULE_PATH), "run", "feat/raspi-fastapi-pipeline",
                                 "--env", "m1", "--", "python", "-c", script],
                                env=env, text=True, capture_output=True, check=True)
        data = json.loads(result.stdout)
        self.assertEqual(data["env"], "m1")
        self.assertEqual(data["venv"], self.environments["m1"])
        self.assertEqual(data["cwd"], str(self.workspace / "branches/feat--raspi-fastapi-pipeline"))

    def test_invalid_env_is_rejected_before_source_initialization(self):
        config = self.write_config()
        env = dict(os.environ, HAI_CONFIG=str(config), HAI_WORKSPACE=str(self.workspace))
        result = subprocess.run([sys.executable, str(MODULE_PATH), "run", "main", "--env", "missing",
                                 "--", "python", "-c", "raise AssertionError('must not execute')"],
                                env=env, text=True, capture_output=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn("Unknown environment", result.stderr)
        self.assertFalse(self.workspace.exists())

    def test_boot_hook_failure_does_not_exit_sourcing_shell_or_change_options(self):
        tools = self.root / "fake-tools"
        tools.mkdir()
        launcher = tools / "hai"
        launcher.write_text("#!/bin/sh\nexit 1\n")
        launcher.chmod(0o755)
        hook = MODULE_PATH.parent / "80-hai-init.sh"
        env = dict(os.environ, PATH=f"{tools}:{os.defpath}")
        result = subprocess.run(["bash", "--noprofile", "--norc", "-c",
                                 'set -eu; before=$-; source "$1"; test "$before" = "$-"; echo survived',
                                 "bash", str(hook)], env=env, text=True, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("survived", result.stdout)
        self.assertIn("setup failed", result.stderr)


